<p>Mozart visited the Augsburg piano maker Johann Andreas Stein in October 1777. In a letter to his father on the 17th, he praised the care Stein took with his instruments, writing that Stein “scrapes and works until the piano can do everything”. Mozart wrote with particular approval of the escapement. The hammer fell away from the string as soon as it had struck, even while the finger held the key down, so that the note could sound without the hammer damping it.</p>
